// chartValuesMarkdown is the page of the values of the chart in dir: a row per property of its values.schema.json, in
// the order of the schema, with the default of its values.yaml. Every property needs a description.
func chartValuesMarkdown(dir string) (string, error) {
	schemaData, err := os.ReadFile(filepath.Join(dir, "values.schema.json"))
	if err != nil {
		return "", err
	}
	var schema yaml.Node
	if err := yaml.Unmarshal(schemaData, &schema); err != nil {
		return "", fmt.Errorf("values.schema.json: %w", err)
	}
	valuesData, err := os.ReadFile(filepath.Join(dir, "values.yaml"))
	if err != nil {
		return "", err
	}
	var values map[string]any
	if err := yaml.Unmarshal(valuesData, &values); err != nil {
		return "", fmt.Errorf("values.yaml: %w", err)
	}
	var b strings.Builder
	fmt.Fprintf(&b, header, "deploy/helm/muster/values.schema.json and values.yaml")
	b.WriteString(chartValuesIntro)
	var errs []error
	if len(schema.Content) == 1 {
		chartRows(&b, field(schema.Content[0], "properties"), "", values, &errs)
	}
	return b.String(), errors.Join(errs...)
}

// chartRows writes a row per property of props and of its nested objects, depth first.
func chartRows(b *strings.Builder, props *yaml.Node, prefix string, values map[string]any, errs *[]error) {
	if props == nil || props.Kind != yaml.MappingNode {
		return
	}
	for i := 0; i+1 < len(props.Content); i += 2 {
		name, prop := props.Content[i].Value, props.Content[i+1]
		path := prefix + name
		description := ""
		if d := field(prop, "description"); d != nil {
			description = d.Value
		}
		if description == "" {
			*errs = append(*errs, fmt.Errorf("values.schema.json: %s has no description", path))
		}
		children := field(prop, "properties")
		def := "—"
		if v, ok := values[name]; ok && children == nil {
			def = "`" + chartDefault(v) + "`"
		}
		fmt.Fprintf(b, "| `%s` | %s | %s | %s |\n", path, cell(schemaType(prop)), cell(def), cell(description))
		nested, _ := values[name].(map[string]any)
		chartRows(b, children, path+".", nested, errs)
	}
}

// schemaType is the type of a property: its type or the types of its alternatives, joined by "or", and its allowed
// values.
func schemaType(prop *yaml.Node) string {
	types := nodeTypes(prop)
	if alts := field(prop, "oneOf"); alts != nil {
		for _, alt := range alts.Content {
			types = append(types, nodeTypes(alt)...)
		}
	}
	t := strings.Join(types, " or ")
	if enum := field(prop, "enum"); enum != nil {
		allowed := make([]string, 0, len(enum.Content))
		for _, v := range enum.Content {
			allowed = append(allowed, "`"+v.Value+"`")
		}
		t += " (" + strings.Join(allowed, ", ") + ")"
	}
	return t
}

func nodeTypes(prop *yaml.Node) []string {
	t := field(prop, "type")
	switch {
	case t == nil:
		return nil
	case t.Kind == yaml.SequenceNode:
		types := make([]string, 0, len(t.Content))
		for _, v := range t.Content {
			types = append(types, v.Value)
		}
		return types
	}
	return []string{t.Value}
}

// field is the value of key in a mapping node, nil when it has none.
func field(n *yaml.Node, key string) *yaml.Node {
	if n == nil || n.Kind != yaml.MappingNode {
		return nil
	}
	for i := 0; i+1 < len(n.Content); i += 2 {
		if n.Content[i].Value == key {
			return n.Content[i+1]
		}
	}
	return nil
}

// chartDefault writes a default of values.yaml: an empty string as "", another string as it is, and anything else as
// compact JSON.
func chartDefault(v any) string {
	switch v := v.(type) {
	case string:
		if v == "" {
			return `""`
		}
		return v
	case nil:
		return "null"
	}
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(v); err != nil {
		return fmt.Sprint(v)
	}
	return strings.TrimSpace(buf.String())
}

// code writes a value in backticks, or a dash when it is empty.
func code(s string) string {
	if s == "" {
		return "—"
	}
	return "`" + s + "`"
}

