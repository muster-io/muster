var cellEscaper = strings.NewReplacer("|", `\|`, "\n", " ")

func main() {
	os.Exit(run(os.Args[1:], os.Stderr))
}

func run(args []string, stderr io.Writer) int {
	flags := flag.NewFlagSet("refgen", flag.ContinueOnError)
	flags.SetOutput(stderr)
	out := flags.String("out", "docs/reference", "the directory of the reference pages")
	cataloguePath := flags.String("catalogue", "design/prd/l1/reference.md",
		"the PRD page whose metrics catalogue the metric registry must match")
	chart := flags.String("chart", "deploy/helm/muster", "the Helm chart whose values the chart values page lists")
	if err := flags.Parse(args); err != nil {
		return 2
	}
	events, eventsErr := logging.Events()
	defs, metricsErr := metrics.Catalogue()
	alerts, alertsErr := internalalerts.Definitions()
	if err := errors.Join(eventsErr, metricsErr, alertsErr); err != nil {
		fmt.Fprintf(stderr, "refgen: invalid registry:\n%v\n", err)
		return 1
	}
	environment, envErr := environmentMarkdown(config.Variables())
	chartValues, chartErr := chartValuesMarkdown(*chart)
	if err := errors.Join(envErr, chartErr); err != nil {
		fmt.Fprintf(stderr, "refgen: %v\n", err)
		return 1
	}
	pages := map[string]string{
		logEventsPage:      logEventsMarkdown(events),
		metricsPage:        metricsMarkdown(defs),
		internalAlertsPage: internalAlertsMarkdown(alerts),
		environmentPage:    environment,
		chartValuesPage:    chartValues,
		apiPage:            apiMarkdown,
		indexPage:          indexMarkdown(),
	}
	if err := os.MkdirAll(*out, 0o750); err != nil {
		fmt.Fprintf(stderr, "refgen: %v\n", err)
		return 1
	}
	for name, content := range pages {
		if err := os.WriteFile(filepath.Join(*out, name), []byte(content), 0o600); err != nil {
			fmt.Fprintf(stderr, "refgen: %v\n", err)
			return 1
		}
	}
	if err := checkCatalogue(*cataloguePath, defs, pages[metricsPage]); err != nil {
		fmt.Fprintf(stderr, "refgen: the metrics differ from the catalogue of %s:\n%v\n", *cataloguePath, err)
		return 1
	}
	return 0
}

func logEventsMarkdown(events []logging.EventInfo) string {
	var b strings.Builder
	fmt.Fprintf(&b, header, "internal/logging/events.go")
	b.WriteString(logEventsIntro)
	for _, e := range events {
		fields := strings.Join(e.Fields, ", ")
		if fields == "" {
			fields = "—"
		}
		levels := make([]string, 0, len(e.Levels))
		for _, l := range e.Levels {
			levels = append(levels, l.String())
		}
		if len(levels) == 0 {
			levels = append(levels, e.Level.String())
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s |\n", e.Name, strings.Join(levels, " or "), fields, e.Capability,
			cell(e.Description))
	}
	return b.String()
}

func metricsMarkdown(defs []metrics.Definition) string {
	var b strings.Builder
	fmt.Fprintf(&b, header, "internal/metrics/catalogue.go")
	b.WriteString(metricsIntro)
	for _, d := range defs {
		names := make([]string, 0, len(d.Labels))
		for _, l := range d.Labels {
			names = append(names, l.Name)
		}
		labels := strings.Join(names, ", ")
		if labels == "" {
			labels = "—"
		}
		leader := "no"
		if d.LeaderOnly {
			leader = "yes"
		}
		description := d.Help
		if len(d.Buckets) > 0 {
			bounds := make([]string, 0, len(d.Buckets))
			for _, v := range d.Buckets {
				bounds = append(bounds, strconv.FormatFloat(v, 'g', -1, 64))
			}
			description += " Buckets (le): " + strings.Join(bounds, ", ") + "."
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s | %s |\n", d.Name, d.Kind, labels, d.Capability, leader, cell(description))
	}
	b.WriteString(`
## Label values

| Metric | Label | Values |
|---|---|---|
`)
	for _, d := range defs {
		for _, l := range d.Labels {
			fmt.Fprintf(&b, "| `%s` | `%s` | %s |\n", d.Name, l.Name, cell(labelValues(l)))
		}
	}
	return b.String()
}

func internalAlertsMarkdown(defs []*internalalerts.Definition) string {
	var b strings.Builder
	fmt.Fprintf(&b, header, "internal/internalalerts/registry.go")
	b.WriteString(internalAlertsIntro)
	for _, d := range defs {
		labels := make([]string, 0, len(d.Labels()))
		for _, l := range d.Labels() {
			labels = append(labels, "`"+l+"`")
		}
		if d.StaticLabels {
			labels = append(labels, "the Integration's Static labels")
		}
		list := strings.Join(labels, ", ")
		if list == "" {
			list = "—"
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | `%s` | %s |\n", d.Name, d.Severity, list, d.Capability, d.Runbook(),
			cell(d.Condition))
	}
	return b.String()
}

func labelValues(l metrics.Label) string {
	switch l.Kind {
	case metrics.LabelClosed:
		values := make([]string, 0, len(l.Values))
		for _, v := range l.Values {
			values = append(values, "`"+v+"`")
		}
		return strings.Join(values, ", ") + " — " + l.Description
	case metrics.LabelEntity:
		return "entity: " + l.Description
	case metrics.LabelInfo:
		return "info: " + l.Description
	}
	return l.Description
}

func cell(s string) string {
	return cellEscaper.Replace(s)
}

